#!/usr/bin/env bash
# Regenerate the zcash-test-vectors fixtures from a pinned revision, and check them against
# the committed artifacts and their provenance manifest.
#
# The Lean models of the deployed primitives are checked against the Rust sources they
# mirror; zcash-test-vectors is the cross-implementation anchor that catches a transcription
# faithfully mirroring a wrong or drifted source (ironwood#204). Each fixture under
# `Zcash/Circuits/Tests/TestVectors/` is the output of `scripts/test_vectors_to_lean.py` on
# one pinned zcash-test-vectors commit, recorded in `MANIFEST.tsv` (path, sha256, generator,
# source, invocation). The converter only parses that checkout — JSON with `json`, the
# generator's constants with `ast` — and never imports or executes it.
#
# Modes:
#   (no argument)    check the manifest, then fetch the pinned revision, regenerate every
#                    fixture, and diff it byte-for-byte against the committed file;
#   --check-manifest no clone: every entry names an existing file whose sha256 matches and
#                    whose source is the pinned revision, and every file carrying the
#                    converter's header has an entry;
#   --write          fetch, regenerate, and overwrite the committed fixtures and manifest
#                    (only once every fixture has regenerated).
#
# Set ZCASH_TEST_VECTORS_SRC to a local checkout or mirror to fetch from (fully offline).
# The pinned commit is fetched by hash with `--depth 1`, which needs git protocol v2 (the
# default since git 2.26) for a local mirror; GitHub allows it either way.
# Run from anywhere; exits non-zero on any violation.
set -euo pipefail
# A relative mirror path is relative to the caller's directory, not the repository root.
if [[ -n "${ZCASH_TEST_VECTORS_SRC:-}" && -d "$ZCASH_TEST_VECTORS_SRC" ]]; then
  ZCASH_TEST_VECTORS_SRC=$(cd "$ZCASH_TEST_VECTORS_SRC" && pwd)
fi
cd "$(dirname "$0")/.."

# The pinned zcash-test-vectors commit (master, 2026-07-01, the merge of PR #131).
ZTV_COMMIT=78321beacb0e0477e33cd002b56585a107c2708c
ZTV_URL=${ZCASH_TEST_VECTORS_SRC:-https://github.com/zcash/zcash-test-vectors.git}

DIR=Zcash/Circuits/Tests/TestVectors
MANIFEST=$DIR/MANIFEST.tsv
# Each fixture: the converter's fixture name and the module it renders.
FIXTURES=(
  "poseidon $DIR/OrchardPoseidonData.lean"
  "generators $DIR/OrchardGeneratorsData.lean"
)
GENERATOR=scripts/test_vectors_to_lean.py
SOURCE=zcash/zcash-test-vectors@$ZTV_COMMIT
HEADER='-- Auto-generated by `scripts/regenerate-test-vectors.sh`'

sha256() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | cut -d' ' -f1
  else
    shasum -a 256 "$1" | cut -d' ' -f1
  fi
}

check_manifest() {
  local status=0 listed="" path digest source invocation f
  [[ -f "$MANIFEST" ]] || { echo "VIOLATION: $MANIFEST is missing" >&2; return 1; }
  while IFS=$'\t' read -r path digest _ source invocation; do
    [[ -z "$path" || "$path" == \#* ]] && continue
    listed+="$path"$'\n'
    if [[ -z "$invocation" ]]; then
      echo "VIOLATION: manifest entry for $path is missing a field" >&2; status=1
    elif [[ "$source" != "$SOURCE" ]]; then
      echo "VIOLATION: $path records source $source, not the pinned $SOURCE" >&2; status=1
    elif [[ ! -f "$path" ]]; then
      echo "VIOLATION: manifest entry $path does not exist" >&2; status=1
    elif [[ "$(sha256 "$path")" != "$digest" ]]; then
      echo "VIOLATION: $path does not match its manifest digest $digest" >&2; status=1
    fi
  done < "$MANIFEST"
  # The rejection direction: every file carrying the converter's header has an entry.
  while IFS= read -r f; do
    if head -n 1 "$f" | grep -qF -e "$HEADER" && ! grep -qxF "$f" <<< "$listed"; then
      echo "VIOLATION: generated fixture $f has no manifest entry" >&2; status=1
    fi
  done < <(find "$DIR" -name '*.lean' | sort)
  return $status
}

case "${1:-}" in
  "") check_manifest ;;
  --check-manifest) check_manifest; exit ;;
  --write) ;;
  *) echo "usage: $0 [--check-manifest | --write]" >&2; exit 2 ;;
esac

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
git init --quiet "$work/ztv"
git -C "$work/ztv" fetch --quiet --depth 1 "$ZTV_URL" "$ZTV_COMMIT"
git -C "$work/ztv" checkout --quiet --detach FETCH_HEAD
[[ "$(git -C "$work/ztv" rev-parse HEAD)" == "$ZTV_COMMIT" ]] \
  || { echo "VIOLATION: checkout is not $ZTV_COMMIT" >&2; exit 1; }

status=0
{
  echo "# Per-artifact provenance for the zcash-test-vectors fixtures (ironwood#204)."
  echo "# Tab-separated: path, sha256, generator, source, invocation."
  echo "# Written and checked by scripts/regenerate-test-vectors.sh."
} > "$work/MANIFEST.tsv"
for entry in "${FIXTURES[@]}"; do
  read -r fixture target <<< "$entry"
  out="$work/$fixture.lean"
  python3 -I "$GENERATOR" "$work/ztv" "$ZTV_COMMIT" "$fixture" > "$out"
  printf '%s\t%s\t%s\t%s\t%s\n' "$target" "$(sha256 "$out")" "$GENERATOR" "$SOURCE" \
    "python3 -I $GENERATOR <checkout> $ZTV_COMMIT $fixture" >> "$work/MANIFEST.tsv"
  if [[ "${1:-}" != --write ]] && ! diff -u "$target" "$out"; then
    echo "VIOLATION: $target does not regenerate byte-for-byte from $SOURCE" >&2
    status=1
  fi
done
if [[ "${1:-}" == --write ]]; then
  for entry in "${FIXTURES[@]}"; do
    read -r fixture target <<< "$entry"
    cp "$work/$fixture.lean" "$target"
    echo "wrote $target"
  done
  cp "$work/MANIFEST.tsv" "$MANIFEST"
  echo "wrote $MANIFEST"
fi
exit $status
